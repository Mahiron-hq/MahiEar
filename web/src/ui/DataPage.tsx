import { offline } from '../lib/offline';
import { wipeEverything } from '../lib/wipe';
import { navigate, settings, toast, updateSettings } from '../state';
import { Button, TopBar } from './common';
import { confirmAsk } from './confirm';
import { Footer, Link, SOURCE_URL } from './Footer';

export function DataPage() {
  const o = offline.value;
  const hasAudio = settings.value.offline && o.done > 0;

  return (
    <div class="screen data-page">
      <TopBar title="О данных" onBack={() => navigate({ name: 'home' })} />
      <article class="prose">
        <h1 class="prose-title">Какие данные хранит MahiEar</h1>
        <p>
          MahiEar работает без регистрации. Почти всё, что нужно для работы, хранится только в вашем браузере на этом
          устройстве, а на сервер попадают лишь обезличенные счётчики.
        </p>

        <h2>На этом устройстве</h2>
        <ul>
          <li>Настройки: задержка показа названия, автопереход, громкость и другие параметры.</li>
          <li>Прогресс подготовки: порядок отрывков, текущее место и ответы «Знал» и «Не знал» в незавершённых прогонах.</li>
          <li>Личная статистика: сколько раз пройден полный прогон и как вы отвечали по каждому отрывку.</li>
          <li>Последний выбор в выборочной подготовке и режимы плейлиста.</li>
          <li>Список отрывков и файлы сайта, чтобы он быстро открывался и работал без интернета.</li>
          <li>При включённом офлайн-режиме: сами аудиофайлы отрывков. Несколько ближайших отрывков сохраняются заранее и без него, чтобы переход был мгновенным.</li>
          <li>Счётчики прослушиваний, которые ещё не успели уйти на сервер, например без интернета.</li>
        </ul>
        <p>Эти данные никуда не передаются, кроме счётчиков из последнего пункта.</p>

        <h2>На сервере</h2>
        <ul>
          <li>Сколько раз прозвучал каждый отрывок.</li>
          <li>Сколько раз всего завершён полный прогон.</li>
          <li>
            Случайные номера событий, чтобы одно и то же прослушивание не посчиталось дважды при повторной отправке. Номер
            создаётся заново для каждого события и не связан ни с устройством, ни с человеком.
          </li>
          <li>Описания технических ошибок сайта для их исправления, без сведений о посетителе.</li>
        </ul>
        <p>
          Учётных записей, постоянных идентификаторов, cookies и журнала посещений нет. Чтобы защитить сайт от перегрузки,
          сервер несколько минут держит IP-адрес в оперативной памяти и никуда его не записывает. Сайт не подключает
          сторонние счётчики, аналитику и рекламу и ничего не загружает с других сайтов. Раз в сутки администратор получает
          сводку перечисленных счётчиков.
        </p>

        <h2>Открытый код</h2>
        <p>
          Исходный код сайта открыт и опубликован на GitHub:{' '}
          <a href={SOURCE_URL} target="_blank" rel="noopener noreferrer">
            github.com/Mahiron-hq/MahiEar
          </a>
          . По нему можно проверить всё, что написано на этой странице.
        </p>

        <h2>Как удалить данные</h2>
        <ul>
          <li>
            Личную статистику и настройки можно сбросить в разделе{' '}
            <Link to={{ name: 'settings' }}>Настройки</Link> кнопками «Сбросить статистику» и «Сбросить настройки».
          </li>
          <li>Сохранённые для работы без интернета отрывки удаляет кнопка ниже. Офлайн-режим при этом выключится.</li>
          <li>Все данные MahiEar на этом устройстве, включая прогресс и файлы сайта, удаляет вторая кнопка ниже.</li>
          <li>
            Также можно удалить данные сайта ear.mahiron.online в настройках браузера, а установленное приложение удалить
            как обычное приложение.
          </li>
        </ul>
        <div class="row-actions">
          <Button
            disabled={!hasAudio}
            onClick={async () => {
              const ok = await confirmAsk(
                'Удалить сохранённые отрывки?',
                'Аудиофайлы будут удалены с устройства, офлайн-режим выключится. Отрывки продолжат загружаться из интернета.',
                'Удалить',
              );
              if (ok) {
                updateSettings({ offline: false });
                toast('Сохранённые отрывки удалены');
              }
            }}
          >
            Удалить сохранённые отрывки
          </Button>
          <Button
            onClick={async () => {
              const ok = await confirmAsk(
                'Удалить все данные MahiEar?',
                'С этого устройства будут удалены настройки, прогресс, личная статистика, сохранённые отрывки и файлы сайта. Отменить это нельзя.',
                'Удалить всё',
              );
              if (ok) void wipeEverything();
            }}
          >
            Удалить все данные MahiEar
          </Button>
        </div>
      </article>
      <Footer />
    </div>
  );
}
